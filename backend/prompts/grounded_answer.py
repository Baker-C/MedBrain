    "no other source information -- no document names, no page numbers, no list of "
    "references at the end.\n\n"
    "If the excerpts do not contain the answer, say that the provided labeling does "
    "not cover it, and write no tags at all in that reply -- an excerpt you did not "
    "answer from must not be cited. Do not answer from general knowledge, and do not "
    "guess."
